    ver = hashlib.md5(open(assets_js, 'rb').read()).hexdigest()[:8]
    s = open(src).read()
    # fonts + assets script
    s = s.replace('family=Barlow+Condensed:wght@500;600;700', 'family=Antonio:wght@600')
    s = s.replace('</head>', f'<script src="cardface-assets.js?v={ver}"></script>\n</head>', 1)
    # drop the "New" banner in the header
    s = re.sub(r'<a class="new-banner".*?</a>', '', s, count=1, flags=re.S)
    # preview marker
    s = s.replace('<meta name="viewport" content="width=device-width, initial-scale=1.0">',
                  '<meta name="viewport" content="width=device-width, initial-scale=1.0">\n<meta name="robots" content="noindex">', 1)
    s = s.replace('<h1 class="chapter-title"><span>Card</span> Scanner</h1>',
                  '<h1 class="chapter-title"><span>Card</span> Scanner <span style="font-size:.5em;color:#7a8aaa">(card-face preview)</span></h1>')
    # CSS
    s = s.replace('</style>', CSS + '\n</style>', 1)
    # buildPillCard
    s = re.sub(r'function buildPillCard\(c\)\{.*?\n  return el;\n\}', lambda m: NEW_BUILD, s, count=1, flags=re.S)
    # makePill
    s = re.sub(r'function makePill\(text,cls,kind\)\{.*?\n\}', lambda m: NEW_MAKEPILL, s, count=1, flags=re.S)
    # counts iterate direct children only (chips contain inner spans now)
    s = s.replace("const pills=document.getElementById(containerid).querySelectorAll('span');",
                  "const pills=document.getElementById(containerid).querySelectorAll(':scope > span');")
