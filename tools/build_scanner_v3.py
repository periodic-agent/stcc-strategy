#!/usr/bin/env python3
"""Build the card-face scanner preview (cards_v3.html + cardface-assets.js).

Takes the LIVE cards.html and rewires filters and card entries into the
card-face design proven in mockups/trait-icons-poc.html:
- rulebook chips for trait + suit filters (medallion/glyph, solid color,
  black-text active state), capsule outlines elsewhere
- entries: name + suit banners (suit glyph), skill banner icons, vertical
  trait pills with medallions (sorted shortest first, kissing overlap),
  true-SVG focus asset in the rounded corner, number chip + meta bottom-left

Assets come from the Traits Cyclopedia extractions (icons/, icons_sf/,
icons_svg/ built by the other tools/ extractors) and are bundled as data
URIs into cardface-assets.js.

Usage: python3 build_scanner_v3.py <live_cards.html> <out_html> <out_assets_js>
"""
import sys, os, glob, json, base64, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_trait_poc import b64_outlined, b64_skill_banner


def build_assets(out_js):
    def b64svg_white(f):
        t = open(f).read()
        t = re.sub(r'fill="rgb\([^"]*\)"', 'fill="#fff"', t)
        return 'data:image/svg+xml;base64,' + base64.b64encode(t.encode()).decode()

    def b64svg(f):
        return 'data:image/svg+xml;base64,' + base64.b64encode(open(f, 'rb').read()).decode()

    trait = {os.path.basename(f)[:-4]: b64_outlined(f, os.path.basename(f)[:-4], border=2)
             for f in sorted(glob.glob('icons/*.png'))}
    trait_chip = {os.path.basename(f)[:-4]: b64_outlined(f, os.path.basename(f)[:-4], border=0)
                  for f in sorted(glob.glob('icons/*.png'))}
    skill = {os.path.basename(f)[:-4].replace('skill-', ''): b64_skill_banner(f)
             for f in sorted(glob.glob('icons_sf/skill-*.png'))}
    def b64svg_focus(f):
        # the asset's near-black corner wedge vanishes against the scanner's
        # dark card background; lift it to a readable navy so the icon
        # visibly connects to both card edges like the print
        t = open(f).read().replace('rgb(35,31,32)', '#39416e')
        return 'data:image/svg+xml;base64,' + base64.b64encode(t.encode()).decode()
    focus = {os.path.basename(f)[:-4].replace('focus-', ''): b64svg_focus(f)
             for f in sorted(glob.glob('icons_svg/focus-*.svg'))}
    suit = {os.path.basename(f)[:-4].replace('suit-', ''): b64svg_white(f)
            for f in sorted(glob.glob('icons_svg/suit-*.svg'))}
    js = ('// Card-face assets extracted from the STCC Traits Cyclopedia v2.1 (vector).\n'
          '// Generated by tools/build_scanner_v3.py. Iconography (c) WizKids.\n'
          'const CARDFACE=' + json.dumps({'trait': trait, 'traitChip': trait_chip,
                                          'skill': skill, 'focus': focus, 'suit': suit}) + ';\n')
    open(out_js, 'w').write(js)
    print(f'assets: {len(trait)} traits, {len(skill)} skills, {len(focus)} focus, {len(suit)} suits -> {out_js} ({len(js)//1024} KB)')


